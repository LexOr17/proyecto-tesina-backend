package com.upemor.app_nutriologo.usuario.enums;

/**
 * Enumeración que define las opciones de género disponibles para los usuarios del sistema.
 * <p>
 * Se utiliza para registrar información demográfica y clínica relevante en perfiles de pacientes,
 * nutriólogos y administradores.
 * </p>
 *
 * @author Sistema Nutriólogo
 * @version 1.0
 */
public enum Genero {

    /**
     * Género masculino.
     */
    MASCULINO,

    /**
     * Género femenino.
     */
    FEMENINO,

    /**
     * Opción para usuarios que se identifican con otra identidad de género o prefieren no especificar.
     */
    OTRO
}
